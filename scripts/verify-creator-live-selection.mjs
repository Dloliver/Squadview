import assert from 'node:assert/strict';
import { chooseCreatorOpeningStreams } from '../src/services/creatorLiveSelection.js';
const select = (props) => chooseCreatorOpeningStreams({ random: () => 0, ...props });
const roster = Array.from({ length: 50 }, (_, i) => `channel${i}`);
const liveLogins = new Set([...roster, 'creator']);
const chosen = select({ roster: ['creator', ...roster.slice(0, 49)], creatorLogin: 'creator', liveLogins, statusComplete: true });
assert.equal(chosen.status, 'ready');
assert.equal(chosen.channels.length, 4);
assert.equal(chosen.channels[0], 'creator');
assert.equal(new Set(chosen.channels).size, 4);
assert(chosen.channels.slice(1).every((c) => roster.includes(c)));
const omitted = select({ roster, creatorLogin: 'creator', liveLogins, statusComplete: true });
assert(!omitted.channels.includes('creator'), 'Creator cannot appear unless approved');
assert(omitted.channels.every((c) => roster.includes(c)), 'Only approved channels may appear');
assert.deepEqual(select({ roster: [], creatorLogin: 'creator', liveLogins: new Set(['creator']), statusComplete: true }), { status: 'none-live', channels: [] });
assert.deepEqual(select({ roster: ['offline'], creatorLogin: 'creator', liveLogins: new Set(['other']), statusComplete: true }), { status: 'none-live', channels: [] });
assert.deepEqual(select({ roster, creatorLogin: 'creator', liveLogins, statusComplete: false }), { status: 'unavailable', channels: [] });
assert.deepEqual(select({ roster: ['channel0'], creatorLogin: 'creator', liveLogins: new Set(['channel0']), statusComplete: true }).channels, ['channel0']);
assert.throws(() => select({ roster: [...roster, 'extra'], creatorLogin: 'creator', liveLogins, statusComplete: true }), /Invalid creator roster/);
console.log('PASS: 50-eligible, maximum-four, creator priority, offline exclusion, unavailable-status fail closed.');
